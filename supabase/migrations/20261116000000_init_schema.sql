-- Internal: random 6-char code from the allowed alphabet (no O/0/I/1).
create function public.generate_event_code()
returns text
language plpgsql volatile
set search_path = public
as $$
declare
  alphabet constant text := 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';
  result text := '';
  i int;
begin
  for i in 1..6 loop
    result := result || substr(alphabet, 1 + floor(random() * length(alphabet))::int, 1);
  end loop;
  return result;
end;
$$;
revoke all on function public.generate_event_code() from public, anon, authenticated;

-- create_event(name, event_date, host_nickname) -> { id, code }
-- Inserts the event and the host's participant row in one transaction.
-- uploads_close_at is set by the events trigger (end of event_date + 7 days, UTC).
create function public.create_event(
  name text,
  event_date date,
  host_nickname text default 'Host'
)
returns jsonb
language plpgsql security definer
set search_path = public
as $$
declare
  v_uid      uuid := auth.uid();
  v_name     text := btrim(create_event.name);
  v_nickname text := coalesce(nullif(btrim(create_event.host_nickname), ''), 'Host');
  v_date     date := create_event.event_date;
  v_code     text;
  v_id       uuid;
  v_attempts int := 0;
begin
  if v_uid is null then
    raise exception 'NOT_AUTHENTICATED' using errcode = '28000';
  end if;
  if v_name is null or char_length(v_name) not between 1 and 60 then
    raise exception 'INVALID_NAME';
  end if;
  if v_date is null then
    raise exception 'INVALID_EVENT_DATE';
  end if;
  if char_length(v_nickname) > 30 then
    raise exception 'INVALID_NICKNAME';
  end if;

  loop
    v_attempts := v_attempts + 1;
    if v_attempts > 20 then
      raise exception 'CODE_GENERATION_FAILED';
    end if;
    v_code := public.generate_event_code();
    begin
      insert into public.events (code, name, event_date, host_id)
      values (v_code, v_name, v_date, v_uid)
      returning events.id into v_id;
      exit;
    exception when unique_violation then
      -- code already taken: try another one
      null;
    end;
  end loop;

  insert into public.participants (event_id, user_id, nickname)
  values (v_id, v_uid, v_nickname);

  return jsonb_build_object('id', v_id, 'code', v_code);
end;
$$;

-- join_event(code, nickname) -> { id, code, name, event_date, uploads_close_at }
-- Errors: EVENT_NOT_FOUND, NICKNAME_TAKEN (also INVALID_NICKNAME, NOT_AUTHENTICATED).
-- Upserts the participant row; re-joining with the same device never counts as "taken".
create function public.join_event(
  code text,
  nickname text
)
returns jsonb
language plpgsql security definer
set search_path = public
as $$
declare
  v_uid      uuid := auth.uid();
  v_code     text := upper(regexp_replace(coalesce(join_event.code, ''), '\s', '', 'g'));
  v_nickname text := btrim(coalesce(join_event.nickname, ''));
  v_event    public.events%rowtype;
begin
  if v_uid is null then
    raise exception 'NOT_AUTHENTICATED' using errcode = '28000';
  end if;

  select * into v_event from public.events e where e.code = v_code;
  if not found then
    raise exception 'EVENT_NOT_FOUND';
  end if;

  if char_length(v_nickname) not between 1 and 30 then
    raise exception 'INVALID_NICKNAME';
  end if;

  -- taken by somebody else (case-insensitive)?
  if exists (
    select 1 from public.participants p
    where p.event_id = v_event.id
      and lower(p.nickname) = lower(v_nickname)
      and p.user_id <> v_uid
  ) then
    raise exception 'NICKNAME_TAKEN';
  end if;

  begin
    insert into public.participants (event_id, user_id, nickname)
    values (v_event.id, v_uid, v_nickname)
    on conflict (event_id, user_id) do update set nickname = excluded.nickname;
  exception when unique_violation then
    -- lost a race against another guest picking the same nickname
    raise exception 'NICKNAME_TAKEN';
  end;

  return jsonb_build_object(
    'id', v_event.id,
    'code', v_event.code,
    'name', v_event.name,
    'event_date', v_event.event_date,
    'uploads_close_at', v_event.uploads_close_at
  );
end;
$$;

revoke all on function public.create_event(text, date, text) from public, anon;
revoke all on function public.join_event(text, text) from public, anon;
grant execute on function public.create_event(text, date, text) to authenticated;
grant execute on function public.join_event(text, text) to authenticated;

-- =====================================================================
-- 6. Storage (DESIGN.md sections 3 and 4)
-- Private bucket; paths {event_id}/{photo_id}.jpg and {event_id}/{photo_id}_thumb.jpg
-- =====================================================================

insert into storage.buckets (id, name, public, file_size_limit)
values ('event-photos', 'event-photos', false, 5242880)
on conflict (id) do update set public = false;

-- select: participant of the event in the path
create policy event_photos_select on storage.objects
  for select to authenticated
  using (
    bucket_id = 'event-photos'
    and public.is_participant(public.storage_event_id(name))
  );

-- insert: participant of the event, path must look like the layout above, uploads open
create policy event_photos_insert on storage.objects
  for insert to authenticated
  with check (
    bucket_id = 'event-photos'
    and public.storage_event_id(name) is not null
    and public.is_participant(public.storage_event_id(name))
    and public.uploads_open(public.storage_event_id(name))
  );

-- no update policy (files are immutable)

-- delete: the uploader or the host. The photos row is deleted BEFORE the files
-- (and does not exist yet when a failed upload is cleaned up), so "uploader" is
-- identified by the storage owner of the object (set by Storage to auth.uid()).
create policy event_photos_delete on storage.objects
  for delete to authenticated
  using (
    bucket_id = 'event-photos'
    and public.storage_event_id(name) is not null
    and (
      public.is_host(public.storage_event_id(name))
      or (
        public.is_participant(public.storage_event_id(name))
        and owner_id = auth.uid()::text
      )
    )
  );

-- =====================================================================
-- 7. Realtime: photos INSERT / DELETE (DESIGN.md section 5, live updates)
-- Realtime applies the select policy, so only participants receive events.
-- Note: with RLS enabled, the "old" record of a DELETE event contains only the
-- primary key (id), so DELETE events cannot be filtered by event_id on the server.
-- REPLICA IDENTITY FULL is kept so the WAL carries the full old row.
-- =====================================================================

alter table public.photos replica identity full;

do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'photos'
  ) then
    alter publication supabase_realtime add table public.photos;
  end if;
end;
$$;
