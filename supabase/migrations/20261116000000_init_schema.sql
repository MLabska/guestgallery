-- =====================================================================
-- 1. Tables (DESIGN.md section 2)
-- =====================================================================

create table public.events (
  id               uuid primary key default gen_random_uuid(),
  code             text not null unique
                     check (code ~ '^[ABCDEFGHJKLMNPQRSTUVWXYZ23456789]{6}$'),
  name             text not null check (char_length(name) between 1 and 60),
  event_date       date not null,
  host_id          uuid not null references auth.users (id) on delete cascade,
  -- always set by the trigger below (end of event_date + 7 days, UTC); never by clients
  uploads_close_at timestamptz not null,
  created_at       timestamptz not null default now()
);
create index events_host_id_idx on public.events (host_id);

create table public.participants (
  id        uuid primary key default gen_random_uuid(),
  event_id  uuid not null references public.events (id) on delete cascade,
  user_id   uuid not null references auth.users (id) on delete cascade,
  nickname  text not null,
  joined_at timestamptz not null default now(),
  -- 1-30 chars and already trimmed, so blank / space-padded nicknames are rejected
  -- even when updated directly through the API (SPEC 2.3)
  constraint participants_nickname_length  check (char_length(nickname) between 1 and 30),
  constraint participants_nickname_trimmed check (nickname = btrim(nickname)),
  constraint participants_event_user_key unique (event_id, user_id)
);
-- Nicknames are unique per event, case-insensitive (SPEC 2.3).
create unique index participants_event_nickname_key
  on public.participants (event_id, lower(nickname));
create index participants_user_id_idx on public.participants (user_id, joined_at desc);

create table public.challenges (
  id          uuid primary key default gen_random_uuid(),
  event_id    uuid not null references public.events (id) on delete cascade,
  title       text not null check (char_length(title) between 1 and 60),
  description text check (description is null or char_length(description) <= 200),
  position    int not null default 0,
  created_at  timestamptz not null default now()
);
create index challenges_event_id_idx on public.challenges (event_id, position);

create table public.photos (
  id           uuid primary key default gen_random_uuid(), -- generated by the client
  event_id     uuid not null references public.events (id) on delete cascade,
  uploader_id  uuid not null references auth.users (id) on delete cascade,
  -- SPEC 5.1: deleting a challenge keeps its photos
  challenge_id uuid references public.challenges (id) on delete set null,
  path         text not null,
  thumb_path   text not null,
  width        int,
  height       int,
  created_at   timestamptz not null default now(),
  -- paths must follow the storage layout of DESIGN.md section 3, so a row can never
  -- point at another photo's files
  constraint photos_paths_match_id check (
    path = event_id::text || '/' || id::text || '.jpg'
    and thumb_path = event_id::text || '/' || id::text || '_thumb.jpg'
  )
);
create index photos_event_created_idx on public.photos (event_id, created_at desc);
create index photos_challenge_id_idx on public.photos (challenge_id);

