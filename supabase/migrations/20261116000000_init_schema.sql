-- events.uploads_close_at = end of (event_date + 7 days) = midnight UTC after that day
-- (SPEC 3.4). Computed on insert and recomputed whenever event_date changes.
create function public.events_set_uploads_close_at()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if tg_op = 'INSERT' then
    new.uploads_close_at := ((new.event_date + 8)::timestamp at time zone 'UTC');
  elsif new.event_date is distinct from old.event_date then
    new.uploads_close_at := ((new.event_date + 8)::timestamp at time zone 'UTC');
  end if;
  return new;
end;
$$;

create trigger events_set_uploads_close_at
  before insert or update on public.events
  for each row execute function public.events_set_uploads_close_at();

-- photos.created_at is always the server time, so a client cannot fake a date.
create function public.photos_force_created_at()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.created_at := now();
  return new;
end;
$$;

create trigger photos_force_created_at
  before insert on public.photos
  for each row execute function public.photos_force_created_at();

revoke all on function public.events_set_uploads_close_at() from public, anon, authenticated;
revoke all on function public.photos_force_created_at() from public, anon, authenticated;

-- =====================================================================
-- 2. Helper functions (DESIGN.md section 4)
-- Security definer so that policies can read participants/events without
-- recursing into their own RLS. They only ever look at auth.uid().
-- =====================================================================

create function public.is_participant(eid uuid)
returns boolean
language sql stable security definer
set search_path = public
as $$
  select exists (
    select 1 from public.participants p
    where p.event_id = eid and p.user_id = auth.uid()
  );
$$;

create function public.is_host(eid uuid)
returns boolean
language sql stable security definer
set search_path = public
as $$
  select exists (
    select 1 from public.events e
    where e.id = eid and e.host_id = auth.uid()
  );
$$;

create function public.uploads_open(eid uuid)
returns boolean
language sql stable security definer
set search_path = public
as $$
  select exists (
    select 1 from public.events e
    where e.id = eid and now() < e.uploads_close_at
  );
$$;

-- Extra helper: true when the challenge is null or belongs to the given event.
create function public.challenge_in_event(cid uuid, eid uuid)
returns boolean
language sql stable security definer
set search_path = public
as $$
  select cid is null or exists (
    select 1 from public.challenges c
    where c.id = cid and c.event_id = eid
  );
$$;

-- Extra helper: event id from a storage object name '{event_id}/{photo_id}.jpg'
-- or '{event_id}/{photo_id}_thumb.jpg' (lower-case UUIDs). Returns null for any other name.
create function public.storage_event_id(object_name text)
returns uuid
language sql immutable
set search_path = public
as $$
  select case
    when object_name ~ '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}(_thumb)?\.jpg$'
    then split_part(object_name, '/', 1)::uuid
  end;
$$;

revoke all on function public.is_participant(uuid) from public, anon;
revoke all on function public.is_host(uuid) from public, anon;
revoke all on function public.uploads_open(uuid) from public, anon;
revoke all on function public.challenge_in_event(uuid, uuid) from public, anon;
revoke all on function public.storage_event_id(text) from public, anon;
grant execute on function public.is_participant(uuid) to authenticated;
grant execute on function public.is_host(uuid) to authenticated;
grant execute on function public.uploads_open(uuid) to authenticated;
grant execute on function public.challenge_in_event(uuid, uuid) to authenticated;
grant execute on function public.storage_event_id(text) to authenticated;

-- =====================================================================
-- 3. Row Level Security (DESIGN.md section 4)
-- Anonymous sign-in users have the Postgres role "authenticated".
-- =====================================================================

alter table public.events       enable row level security;
alter table public.participants enable row level security;
alter table public.challenges   enable row level security;
alter table public.photos       enable row level security;

-- No access for signed-out callers; events/participants rows are created only by the
-- create_event / join_event RPCs (no insert privilege) and never deleted (not in v1);
-- photos cannot be updated; participants/events may only update the allowed columns.
revoke all on public.events, public.participants, public.challenges, public.photos from anon;
revoke insert, delete on public.events, public.participants from authenticated;
revoke update on public.photos from authenticated;
revoke update on public.events, public.participants from authenticated;
grant update (name, event_date) on public.events to authenticated;
grant update (nickname) on public.participants to authenticated;

-- events: select participant | insert ONLY via create_event (no policy, no privilege)
--         | update host (only name, event_date) | no delete
create policy events_select on public.events
  for select to authenticated
  using (public.is_participant(id));
create policy events_update on public.events
  for update to authenticated
  using (public.is_host(id))
  with check (public.is_host(id));

-- participants: select same event | insert ONLY via join_event/create_event (no policy)
--               | update own row (nickname) | no delete
create policy participants_select on public.participants
  for select to authenticated
  using (public.is_participant(event_id));
create policy participants_update on public.participants
  for update to authenticated
  using (user_id = auth.uid())
  with check (user_id = auth.uid());

-- challenges: select participant | insert/update/delete host
create policy challenges_select on public.challenges
  for select to authenticated
  using (public.is_participant(event_id));
create policy challenges_insert on public.challenges
  for insert to authenticated
  with check (public.is_host(event_id));
create policy challenges_update on public.challenges
  for update to authenticated
  using (public.is_host(event_id))
  with check (public.is_host(event_id));
create policy challenges_delete on public.challenges
  for delete to authenticated
  using (public.is_host(event_id));

-- photos: select participant
--         insert participant, own uploader_id, challenge from same event, uploads open
--         no update | delete own photo or host
create policy photos_select on public.photos
  for select to authenticated
  using (public.is_participant(event_id));
create policy photos_insert on public.photos
  for insert to authenticated
  with check (
    public.is_participant(event_id)
    and uploader_id = auth.uid()
    and public.challenge_in_event(challenge_id, event_id)
    and public.uploads_open(event_id)
  );
create policy photos_delete on public.photos
  for delete to authenticated
  using (uploader_id = auth.uid() or public.is_host(event_id));

-- =====================================================================
-- 4. View: photos with the uploader's nickname (DESIGN.md section 2)
-- security_invoker = the caller's RLS applies to photos and participants.
-- =====================================================================

create view public.photos_with_author
with (security_invoker = true)
as
select
  ph.id,
  ph.event_id,
  ph.uploader_id,
  ph.challenge_id,
  ph.path,
  ph.thumb_path,
  ph.width,
  ph.height,
  ph.created_at,
  pa.nickname as author_nickname
from public.photos ph
left join public.participants pa
  on pa.event_id = ph.event_id and pa.user_id = ph.uploader_id;

revoke all on public.photos_with_author from anon;
grant select on public.photos_with_author to authenticated;

